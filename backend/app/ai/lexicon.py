_LOADED = False


def load_lexicon() -> None:
    """把行业术语加入 jieba 词典；重复调用无害。"""
    global _LOADED
    if _LOADED:
        return
    for term in DOMAIN_TERMS:
        jieba.add_word(term, freq=1000)
    _LOADED = True


def unload_lexicon() -> None:
    """移除行业术语，用于对比评测（评测脚本会还原基线）。"""
    global _LOADED
    for term in DOMAIN_TERMS:
        jieba.del_word(term)
    _LOADED = False


def expand_query(text: str | None) -> str:
    """把口语说法扩展成规范表述，原始文字保留在前。"""
    if not text:
        return ""
    extra: list[str] = []
    for phrase, canonical in SYNONYMS.items():
        if phrase in text:
            extra.extend(word for word in canonical if word not in extra)
    if not extra:
        return text
    return f"{text} {' '.join(extra)}"
