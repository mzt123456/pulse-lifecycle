@dataclass(frozen=True)
class SyntheticCase:
    """一条仿真案例，口语表述用于构造评测查询。"""

    fault_type: str
    instrument_type: str
    description: str
    colloquial: str
    cause: str
    solution: str
    doc_id: str

    def to_document(self) -> CaseDocument:
        return CaseDocument(
            source=SOURCE_SYNTHETIC,
            doc_id=self.doc_id,
            title=f"{self.fault_type}｜{self.description}",
            text=render_fault_text(
                description=self.description,
                cause=self.cause,
                solution=self.solution,
                fault_type=self.fault_type,
                instrument_type=self.instrument_type,
            ),
            payload={
                "fault_type": self.fault_type,
                "instrument_type": self.instrument_type,
                "cause": self.cause,
                "solution": self.solution,
            },
        )


def synthetic_cases() -> list[SyntheticCase]:
    """按蓝图展开仿真案例；仪器类型轮转分配，保证四类都有覆盖。"""
    cases: list[SyntheticCase] = []
    index = 0
    for fault_type, blueprints in BLUEPRINTS.items():
        for description, colloquial, cause, solution in blueprints:
            index += 1
            cases.append(
                SyntheticCase(
                    fault_type=fault_type,
                    instrument_type=INSTRUMENT_TYPES[index % len(INSTRUMENT_TYPES)],
                    description=description,
                    colloquial=colloquial,
                    cause=cause,
                    solution=solution,
                    doc_id=f"synthetic:{fault_type}:{index:03d}",
                )
            )
    return cases


def build_synthetic_case_documents() -> list[CaseDocument]:
    return [case.to_document() for case in synthetic_cases()]
